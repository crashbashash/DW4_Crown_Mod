//! Emit the small scalar IPC contract from Rust's serialized field names and defaults.
//! The populated sample supplies the type of nullable fields; unsupported shapes
//! fail instead of silently emitting an inaccurate TypeScript declaration.
use dw4vhp_core::options::PatchSelection;
use serde_json::Value;

fn main() {
    let defaults = serde_json::to_value(PatchSelection::default()).unwrap();
    let sample = serde_json::to_value(PatchSelection {
        enemy_seed: Some(0),
        ..Default::default()
    })
    .unwrap();
    let mut fields: Vec<_> = sample.as_object().unwrap().iter().collect();
    fields.sort_by_key(|(name, _)| *name);
    println!("// Generated by npm run bindings from options::PatchSelection. Do not edit.\nexport interface PatchSelection {{");
    for (name, value) in &fields {
        let ty = match value {
            Value::Bool(_) => "boolean",
            Value::Number(_) => "number",
            _ => panic!("populate scalar sample field {name} before exporting its type"),
        };
        let nullable = if defaults[*name].is_null() {
            " | null"
        } else {
            ""
        };
        println!("  {name}: {ty}{nullable};");
    }
    println!("}}\n\nexport const DEFAULT_PATCH_SELECTION: Readonly<PatchSelection> = {{");
    for (name, _) in &fields {
        println!("  {name}: {},", defaults[*name]);
    }
    println!("}};");
}
