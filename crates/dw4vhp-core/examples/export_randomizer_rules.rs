//! Render the public protection catalogue from the policy consumed by the planner.
use dw4vhp_core::crown::encounters::{importable_models, protected_encounters};
fn main() {
    println!("# Randomizer encounter rules\n\n<!-- Generated by npm run docs:rules. Edit crown/encounters.rs and regenerate. -->\n");
    println!("## Importable enemy models\n\nThe following native model families can be imported, in selection order:\n");
    for model in importable_models() {
        println!("- `{model}`");
    }
    println!("\nRegular MR04 (`e_mecha4`) is included; the separate boss model (`e_mecha4bs`) is not an import candidate.\n");
    println!("## Fixed generator protections\n\n| Stage | Pack | Generators | Reason |\n| --- | --- | --- | --- |");
    for rule in protected_encounters() {
        let generators = rule
            .generators
            .iter()
            .map(|s| format!("`{s}`"))
            .collect::<Vec<_>>()
            .join(", ");
        println!(
            "| {} (`{}`) | {} | {} | {} |",
            rule.name, rule.stage, rule.pack_entry, generators, rule.reason
        );
    }
    println!("\n## Additional protections\n\nThese fixed records are not the entire exclusion policy. Authored spawn sequences keep their original models. Stage scripts that address an enemy family by native model name protect that family on the floor, except for explicitly reviewed exceptions. Boss families and native scripted encounters remain protected. Kill-count quests restrict replacements to their compatible resident families.\n\nThe developer world, practice stage and final-boss stages are excluded from enemy randomization. Cosmetic crowns are independent of these enemy-replacement rules.\n\nChanging eligibility, ordering or exceptions can change seeded output and requires a randomizer rules-version decision plus corresponding real-disc validation.");
}
